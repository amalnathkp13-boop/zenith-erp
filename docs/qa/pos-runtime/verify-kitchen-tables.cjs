// Called by the disposable runtime verifier; every mutation uses the real POST transition.
module.exports=async function({a,foreign,base,post,rows,count,check}) {
 const label='QA_KITCHEN_ROUTE_'+Date.now();
 await post('Kitchen/Tables','createTable',{facilityId:'POS_QA_A_FAC',tableNumber:label,seatingCapacity:'4'});
 const table=rows('restaurant_table',`table_number='${label}'`)[0];
 const page=await a.c.newPage();
 await page.goto(base+'/apps/zenith/pos/Kitchen/Tables');
 await page.waitForFunction(()=>typeof tmAddSave==='function');
 await page.evaluate(id=>tmSelect(id),table.table_id);
 const open=page.getByRole('button',{name:'Open Billing',exact:true});
 await Promise.all([page.waitForNavigation(),open.click()]);
 check('Open Billing opens KOT Billing with the selected table',page.url().includes('/Kitchen/KotBilling')&&await page.locator('#kb-table').inputValue()===table.table_id);
 await page.goto(base+'/apps/zenith/pos/Kitchen/Tables');
 await page.waitForFunction(()=>typeof tmAddSave==='function');
 await page.evaluate(()=>tmModal(true));await page.locator('#tm-f-num').fill('Missing facility');
 await page.locator('#tm-addsave').click();
 check('missing facility stays in the form with an inline error and enabled save',await page.locator('#tm-f-fac').getAttribute('aria-invalid')==='true'&&!await page.locator('#tm-addsave').isDisabled());
 const payload={itemsJson:JSON.stringify([{productId:'POS_QA_A_P18',quantity:1}]),tableId:table.table_id,tableNumber:label,orderType:'Dine In'};
 await post('Kitchen/KotBilling','saveDraft',payload);
 check('saving a draft does not occupy a table',rows('restaurant_table',`table_id='${table.table_id}'`)[0].status_id==='TblAvailable');
 const before=count('kitchen_order_ticket','1=1');
 await post('Kitchen/KotBilling','createKot',payload,foreign);
 check('another shop cannot submit an order for this table',count('kitchen_order_ticket','1=1')===before);
 await post('Kitchen/KotBilling','createKot',payload);
 check('sending an order marks its selected table occupied',rows('restaurant_table',`table_id='${table.table_id}'`)[0].status_id==='TblOccupied');
 await post('Kitchen/Tables','closeTable',{tableId:table.table_id});
 check('closing a table with active kitchen orders is rejected',rows('restaurant_table',`table_id='${table.table_id}'`)[0].status_id==='TblOccupied');
 await post('Kitchen/Tables','deleteTable',{tableId:table.table_id});
 check('an occupied table cannot be deleted',count('restaurant_table',`table_id='${table.table_id}'`)===1);
 const kot=rows('kitchen_order_ticket',`table_number='${label}' AND status_id='KotNew'`)[0];
 await post('Kitchen/KotBilling','createKot',payload);
 const second=rows('kitchen_order_ticket',`table_number='${label}' AND status_id='KotNew'`).find(k=>k.kot_id!==kot.kot_id);
 await post('Kitchen/KitchenDisplay','updateStatus',{kotId:kot.kot_id,statusId:'KotCancelled'});
 check('cancelling one order keeps a table occupied while another is active',rows('restaurant_table',`table_id='${table.table_id}'`)[0].status_id==='TblOccupied');
 await post('Kitchen/KitchenDisplay','updateStatus',{kotId:second.kot_id,statusId:'KotCancelled'});
 check('cancelling the last active order releases its table',rows('restaurant_table',`table_id='${table.table_id}'`)[0].status_id==='TblAvailable');
 await post('Kitchen/Tables','deleteTable',{tableId:table.table_id},foreign);
 check('another shop cannot delete an available table',count('restaurant_table',`table_id='${table.table_id}'`)===1);
 await post('Kitchen/Tables','deleteTable',{tableId:'*'});
 check('wildcard table deletion is rejected',count('restaurant_table',`table_id='${table.table_id}'`)===1);
 await post('Kitchen/Tables','deleteTable',{tableId:table.table_id});
 check('available table deletion supplies its exact primary key',count('restaurant_table',`table_id='${table.table_id}'`)===0);
 await page.close();
};
